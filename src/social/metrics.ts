export type Face = keyof typeof WIDTHS;

const tables = Object.fromEntries(
  Object.entries(WIDTHS).map(([face, widths]) => [
    face,
    new Map([...CHARS].map((char, index) => [char, widths[index]])),
  ])
) as unknown as Record<Face, Map<string, number>>;

function charWidth(char: string, face: Face): number {
  const table = tables[face];
  return (
    table.get(char) ??
    table.get(char.normalize('NFD')[0]) ??
    (char === '\u00A0' ? table.get(' ') : undefined) ??
    table.get('M')!
  );
}

// Width of a text on one line, in pixels.
export function textWidth(text: string, fontSize: number, face: Face, letterSpacing = 0): number {
  let width = 0;
  for (const char of text) width += (charWidth(char, face) / 1000) * fontSize + letterSpacing;
  return width;
}
